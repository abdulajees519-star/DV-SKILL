import matplotlib.pyplot as plt
import pandas as pd
import numpy as np
import seaborn as sns
df=pd.read_csv('kc_house_data.csv')

df.head()

df.tail()

df.info()

df.describe()

df.shape

df.columns

df.isnull().sum()

df.duplicated

df['features']=df['bedrooms'] + df['bathrooms'] + df['sqft_living']
display(df[['bedrooms', 'bathrooms', 'sqft_living', 'features']].head())

df['date']=pd.to_datetime(df['date'])

df['yr_built']=pd.to_datetime(df['yr_built'])

df['price_per_sqft'] = df['price'] / df['sqft_living']
display(df[['price', 'sqft_living', 'price_per_sqft']].head())

df['Is_renovated']=df['yr_renovated']

df['Is_renovated'].head()

zero_bedrooms = (df['bedrooms'] == 0).sum()
zero_bathrooms = (df['bathrooms'] == 0).sum()
print(zero_bedrooms)
print(zero_bathrooms)

if zero_bedrooms > 0:
    df.loc[df['bedrooms'] == 0, 'bedrooms'] = df['bedrooms'].median()
if zero_bathrooms > 0:
    df.loc[df['bathrooms'] == 0, 'bathrooms'] = df['bathrooms'].median()

df['date'] = pd.to_datetime(df['date'])

if pd.api.types.is_datetime64_any_dtype(df['yr_built']):
    df['yr_built_year'] = df['yr_built'].dt.year
else:
    df['yr_built_year'] = pd.to_datetime(df['yr_built'], format='%Y', errors='coerce').dt.year.fillna(df['yr_built']).astype(int)

df['house_age'] = df['date'].dt.year - df['yr_built_year']
df['effective_year'] = np.where(df['yr_renovated'] > 0, df['yr_renovated'], df['yr_built_year'])
df['years_since_renovation'] = df['date'].dt.year - df['effective_year']

display(df[['date', 'yr_built_year', 'yr_renovated', 'house_age', 'years_since_renovation']].head())

df['price_per_sqft_living'] = df['price'] / df['sqft_living']
df['price_per_sqft_lot'] = df['price'] / df['sqft_lot']

display(df[['price', 'sqft_living', 'price_per_sqft_living', 'sqft_lot', 'price_per_sqft_lot']].head())

plt.figure(figsize=(10, 5))
sns.boxplot(x=df['price'])
plt.show()

Q1 = df['price'].quantile(0.25)
Q3 = df['price'].quantile(0.75)
IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

outliers = df[(df['price'] < lower_bound) | (df['price'] > upper_bound)]
print(lower_bound)
print(upper_bound)
print(len(outliers))